"""Виконання перевірок зі специфікацій (specs.py): каталог PostgreSQL і поведінка обмежень."""
import inspect
import re

import pytest

import pgutil
from pgutil import CODES, attempt, canon, columns, constraints, tables

FUNCS = {9: ("violations",), 10: ("create_script", "drop_script")}


def fail(message):
    pytest.fail(message, pytrace=False)


def call(mod, name, task, set_no):
    """Викликає функцію варіанта. Еталон приймає номер набору; студентська функція без параметрів
    працює для набору, що випливає з константи VARIANT."""
    fn = getattr(mod, name, None)
    if fn is None:
        fail(f"У файлі варіанта немає функції {name}()")
    if inspect.signature(fn).parameters:
        return fn(set_no)
    variant = getattr(mod, "VARIANT", 0)
    if variant:
        if (variant - 1) // 3 + 1 != task:
            fail(f"VARIANT = {variant} не відповідає задачі {task}: файл variant_{task:02d}.py призначений "
                 f"для варіантів {3 * task - 2}-{3 * task}")
        if (variant - 1) % 3 + 1 != set_no:
            pytest.skip("перевірка іншого набору даних")
    try:
        return fn()
    except NotImplementedError:
        fail(f"Функція {name}() ще не реалізована (NotImplementedError)")


def prepare(db, mod, task, set_no, spec):
    """Готує базу: початковий стан із умови (за наявності) і скрипт студента. Для задачі 9 повертає список команд."""
    if spec.get("setup"):
        db.run(spec["setup"])
    if task == 9:
        statements = call(mod, "violations", task, set_no)
        if not isinstance(statements, (list, tuple)) or not all(isinstance(s, str) for s in statements):
            fail("violations() має повертати список рядків з SQL-командами")
        return list(statements)
    name = "create_script" if task == 10 else "script"
    sql = call(mod, name, task, set_no)
    if not isinstance(sql, str):
        fail(f"{name}() має повертати рядок з SQL-скриптом")
    try:
        db.run(sql)
    except pgutil.ScriptError as error:
        fail(f"SQL-скрипт завершився помилкою {error}")
    return sql


def run_case(db, mod, task, set_no, spec, check):
    prepared = prepare(db, mod, task, set_no, spec)
    HANDLERS[check["type"]](db, check, prepared, mod, task, set_no)


def need_table(db, table):
    got = columns(db, table)
    if not got:
        fail(f"Таблицю {table} не створено")
    return got


def h_tables(db, c, prepared, *_):
    got = tables(db)
    if got != c["tables"]:
        fail(f"Очікувані таблиці {c['tables']}, у схемі {got}")


def h_columns(db, c, prepared, *_):
    got = need_table(db, c["table"])
    errors = []
    for name, (type_name, notnull) in c["cols"].items():
        if name not in got:
            errors.append(f"немає стовпця {name}")
            continue
        if got[name]["type"] != canon(type_name):
            errors.append(f"{name}: тип {got[name]['type']}, очікується {canon(type_name)}")
        if notnull is not None and got[name]["notnull"] != notnull:
            errors.append(f"{name}: " + ("має бути NOT NULL" if notnull else "не повинен бути NOT NULL"))
    if c["exact"]:
        extra = sorted(set(got) - set(c["cols"]))
        if extra:
            errors.append(f"зайві стовпці {extra}")
    if errors:
        fail(f"Таблиця {c['table']}: " + "; ".join(errors))


def h_pk(db, c, prepared, *_):
    need_table(db, c["table"])
    found = [x for x in constraints(db, c["table"]) if x["type"] == "p"]
    if not found:
        fail(f"У таблиці {c['table']} немає первинного ключа")
    if found[0]["cols"] != c["cols"]:
        fail(f"Первинний ключ {c['table']} на стовпцях {found[0]['cols']}, очікується {c['cols']}")
    if c["name"] and found[0]["name"] != c["name"]:
        fail(f"Ім'я первинного ключа {found[0]['name']}, очікується {c['name']}")


def h_identity(db, c, prepared, *_):
    got = need_table(db, c["table"])
    if c["col"] not in got:
        fail(f"Немає стовпця {c['col']}")
    kind = got[c["col"]]["identity"]
    word = {"a": "GENERATED ALWAYS AS IDENTITY", "d": "GENERATED BY DEFAULT AS IDENTITY"}
    if kind != c["kind"]:
        fail(f"{c['table']}.{c['col']}: потрібно {word[c['kind']]}")


def find(db, table, name, kind):
    need_table(db, table)
    for item in constraints(db, table):
        if item["name"] == name and item["type"] == kind:
            return item
    label = {"f": "зовнішнього ключа", "u": "обмеження UNIQUE", "c": "обмеження CHECK"}[kind]
    names = [x["name"] for x in constraints(db, table) if x["type"] == kind]
    fail(f"У таблиці {table} немає {label} з іменем {name} (є: {names or 'жодного'})")


def h_fk(db, c, prepared, *_):
    item = find(db, c["table"], c["name"], "f")
    errors = []
    if item["cols"] != c["cols"]:
        errors.append(f"стовпці {item['cols']}, очікується {c['cols']}")
    if item["ref"] != c["ref"] or item["refcols"] != c["refcols"]:
        errors.append(f"посилання на {item['ref']}{item['refcols']}, очікується {c['ref']}{c['refcols']}")
    if CODES[item["on_delete"]] != c["on_delete"]:
        errors.append(f"ON DELETE {CODES[item['on_delete']]}, очікується {c['on_delete']}")
    if CODES[item["on_update"]] != c["on_update"]:
        errors.append(f"ON UPDATE {CODES[item['on_update']]}, очікується {c['on_update']}")
    if item["deferrable"] != c["deferrable"]:
        errors.append("має бути DEFERRABLE" if c["deferrable"] else "не повинен бути DEFERRABLE")
    if item["deferred"] != c["deferred"]:
        errors.append("має бути INITIALLY DEFERRED" if c["deferred"] else "не повинен бути INITIALLY DEFERRED")
    if errors:
        fail(f"Зовнішній ключ {c['name']}: " + "; ".join(errors))


def h_unique(db, c, prepared, *_):
    item = find(db, c["table"], c["name"], "u")
    if item["cols"] != c["cols"]:
        fail(f"UNIQUE {c['name']} на стовпцях {item['cols']}, очікується {c['cols']}")
    if bool(item["nnd"]) != c["nnd"]:
        fail(f"UNIQUE {c['name']}: " + ("потрібно NULLS NOT DISTINCT" if c["nnd"] else "NULLS NOT DISTINCT не потрібне"))


def h_check(db, c, prepared, *_):
    find(db, c["table"], c["name"], "c")


def h_coltype(db, c, prepared, *_):
    got = need_table(db, c["table"])
    if c["col"] not in got:
        fail(f"Немає стовпця {c['table']}.{c['col']}")
    if got[c["col"]]["type"] != canon(c["ctype"]):
        fail(f"{c['table']}.{c['col']}: тип {got[c['col']]['type']}, очікується {canon(c['ctype'])}")


def h_enum(db, c, prepared, *_):
    labels = [r[0] for r in db.rows(
        """SELECT e.enumlabel FROM pg_enum e JOIN pg_type t ON t.oid = e.enumtypid
           WHERE t.typname = %s AND t.typnamespace = current_schema()::regnamespace ORDER BY e.enumsortorder""",
        (c["name"],))]
    if not labels:
        fail(f"Тип ENUM {c['name']} не створено")
    if labels != c["labels"]:
        fail(f"ENUM {c['name']}: значення {labels}, очікується {c['labels']} (порядок важливий)")


def h_domain(db, c, prepared, *_):
    row = db.rows(
        """SELECT format_type(typbasetype, typtypmod) FROM pg_type
           WHERE typname = %s AND typtype = 'd' AND typnamespace = current_schema()::regnamespace""", (c["name"],))
    if not row:
        fail(f"Домен {c['name']} не створено (CREATE DOMAIN)")
    if row[0][0] != canon(c["base"]):
        fail(f"Домен {c['name']} на типі {row[0][0]}, очікується {canon(c['base'])}")


def h_generated(db, c, prepared, *_):
    got = need_table(db, c["table"])
    if c["col"] not in got:
        fail(f"Немає стовпця {c['table']}.{c['col']}")
    kind = got[c["col"]]["generated"]
    word = {"s": "STORED", "v": "VIRTUAL", "": "звичайний"}
    if kind != c["kind"]:
        fail(f"{c['table']}.{c['col']}: згенерований стовпець {word[c['kind']]}, а в схемі {word[kind]}")


def explain(out):
    return f"{out.state} {out.message.splitlines()[0]}" if out.state else "помилки не було"


def h_probe(db, c, prepared, *_):
    out = attempt(db, c["setup"], c["stmt"], c["verify"])
    if out.state != c["state"]:
        want = c["state"] or "успішне виконання"
        fail(f"Команда {c['stmt'] if isinstance(c['stmt'], str) else c['stmt'][-1]!r}: очікувався результат "
             f"{want}, отримано: {explain(out)}")
    if c["constraint"] and out.constraint != c["constraint"]:
        fail(f"Помилка {out.state} має спрацювати на обмеженні {c['constraint']}, а спрацювала на {out.constraint}")
    if c["column"] and out.column != c["column"]:
        fail(f"Помилка {out.state} має стосуватися стовпця {c['column']}, а стосується {out.column}")
    if c["verify"] and str(out.value) != str(c["expect"]):
        fail(f"Після команди запит {c['verify']!r} має повернути {c['expect']!r}, а повернув {out.value!r}")


def h_data(db, c, prepared, *_):
    got = db.value(c["sql"])
    if str(got) != str(c["expect"]):
        fail(f"Запит {c['sql']!r} має повернути {c['expect']!r}, а повернув {got!r}")


def h_violation(db, c, statements, *_):
    if len(statements) <= c["index"]:
        fail(f"Потрібна команда №{c['index'] + 1}, а у списку лише {len(statements)}")
    if c.get("verb") and not re.match(rf"\s*({c['verb']})\b", statements[c["index"]], re.I):
        fail(f"Команда №{c['index'] + 1} має починатися з {c['verb'].replace('|', ' або ')}")
    out = attempt(db, [], statements[c["index"]])
    if out.state != c["state"]:
        fail(f"Команда №{c['index'] + 1} має завершитися помилкою {c['state']}, отримано: {explain(out)}")
    if c["name"] and c["name"] not in (out.constraint, out.column):
        fail(f"Команда №{c['index'] + 1}: помилка {out.state} має стосуватися {c['name']}, "
             f"а стосується {out.constraint or out.column}")


def h_txn(db, c, prepared, *_):
    out = attempt(db, [], c["stmts"], c["verify"], commit=True)
    if out.state != c["state"]:
        want = c["state"] or "успішне виконання"
        fail(f"Транзакція {c['stmts']}: очікувався результат {want}, отримано: {explain(out)}")
    if c["verify"] and str(out.value) != str(c["expect"]):
        fail(f"Після транзакції запит {c['verify']!r} має повернути {c['expect']!r}, а повернув {out.value!r}")


def h_drop(db, c, prepared, mod, task, set_no):
    sql = call(mod, "drop_script", task, set_no)
    if not isinstance(sql, str):
        fail("drop_script() має повертати рядок з SQL-скриптом")
    try:
        db.run(sql)
    except pgutil.ScriptError as error:
        fail(f"drop_script() завершився помилкою {error}")
    left = tables(db)
    if left:
        fail(f"Після drop_script() у схемі лишилися таблиці {left}")


def h_nocascade(db, c, prepared, mod, task, set_no):
    sql = call(mod, "drop_script", task, set_no)
    if isinstance(sql, str) and re.search(r"\bcascade\b", sql, re.I):
        fail("У drop_script() не можна використовувати CASCADE: порядок видалення має враховувати залежності")


HANDLERS = {
    "tables": h_tables, "columns": h_columns, "pk": h_pk, "identity": h_identity, "fk": h_fk, "unique": h_unique,
    "check": h_check, "coltype": h_coltype, "enum": h_enum, "domain": h_domain, "generated": h_generated,
    "probe": h_probe, "data": h_data, "violation": h_violation, "txn": h_txn, "drop": h_drop,
    "nocascade": h_nocascade,
}
